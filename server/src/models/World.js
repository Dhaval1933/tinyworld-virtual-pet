const mongoose = require('mongoose');

/**
 * Schema for a single placed item inside a room.
 */
const placedItemSchema = new mongoose.Schema(
  {
    placementId: {
      type: String,
      required: true, // UUID generated by frontend
    },
    itemId: {
      type: String,
      required: true, // References ShopItem.itemId
    },
    x: {
      type: Number,
      required: true,
      min: 0,
      max: 1, // Normalized 0–1 coordinate
    },
    y: {
      type: Number,
      required: true,
      min: 0,
      max: 1,
    },
    rotation: {
      type: Number,
      default: 0,
      min: 0,
      max: 360,
    },
    layer: {
      type: Number,
      default: 0, // z-order for overlapping items
    },
  },
  { _id: false }
);

const worldSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      unique: true,
    },
    roomTheme: {
      type: String,
      default: 'cozy',
    },
    wallStyle: {
      type: String,
      default: 'default',
    },
    floorStyle: {
      type: String,
      default: 'default',
    },
    roomLayout: {
      type: [placedItemSchema],
      default: [],
      validate: {
        validator: function (v) {
          return v.length <= 30;
        },
        message: 'Room cannot have more than 30 items.',
      },
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model('World', worldSchema);
